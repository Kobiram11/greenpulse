const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const nodes = JSON.parse(fs.readFileSync(path.join(__dirname, '../node-red/greenpulse-flow.json')));
const ids = new Set(nodes.map(n => n.id));
assert.equal(ids.size, nodes.length);
for (const n of nodes) for (const wires of n.wires || []) for (const id of wires) assert(ids.has(id));
const fnNode = nodes.find(n => n.type === 'function');
const fn = new Function('msg', 'flow', 'node', fnNode.func);
let state;
const flow = { get: () => state, set: (key, value) => { state = value; } };
const node = { warn: () => {} };
let result = fn({topic:'greenpulse/device/plant01/sensors', payload:JSON.stringify({ts:Math.floor(Date.now()/1000),soil:{moisture:42},air:{humidity:72}})}, flow, node);
assert.equal(result.payload.sensors.data.soil.moisture, 42);
assert.equal(result.payload.device, 'online');
assert.equal(fn({topic:'greenpulse/device/plant01/sensors', payload:'bad-json'},flow,node),null);
result = fn({topic:'greenpulse/device/plant01/status',payload:{online:false}},flow,node);
assert.equal(result.payload.device,'offline / stale');
result = fn({status:{text:'connected'}},flow,node);
assert.equal(result.payload.broker,'connected');
const widget = nodes.find(n=>n.type==='ui-template');
const script = widget.format.match(/<script>([\s\S]*?)<\/script>/)[1];
new Function(script.replace('export default', 'return'))();
assert(!widget.format.includes('v-html'));
console.log('Dashboard flow: links, aggregation, invalid JSON, disconnect state, script syntax and text escaping checks passed');
